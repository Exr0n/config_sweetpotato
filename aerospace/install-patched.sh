#!/bin/bash
# Build and install the patched AeroSpace (0.21.3-Beta-exrpatch.1) over the cask app.
# Upstream Monitor.activeWorkspace recurses forever on a stale monitor during a display
# refresh (stack-overflow crash, seen 2026-08-10, 08-12 on pinktop and 2026-10-26 on
# sweetpotato3). patches/*.patch fixes it. Needs only Command Line Tools (swift), no Xcode.
# Re-run after any `brew upgrade --cask aerospace`, which puts the stock app back.
set -euo pipefail
UPSTREAM_COMMIT=d56e1637c3a1ed660d0cadd7534e94fb3218d1c3   # v0.21.3-Beta, what the cask ships
VERSION=0.21.3-Beta-exrpatch.1
HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="${AEROSPACE_SRC:-$HOME/src/AeroSpace}"
APP=/Applications/AeroSpace.app
ROLLBACK="$HOME/Library/Application Support/AeroSpaceRollback"

[ -d "$SRC/.git" ] || git clone -q https://github.com/nikitabobko/AeroSpace.git "$SRC"
cd "$SRC"
git fetch -q origin 2>/dev/null || true
git checkout -q -f "$UPSTREAM_COMMIT"
git clean -qfd Sources
for p in "$HERE"/patches/*.patch; do git apply "$p"; done
printf '// FILE IS GENERATED BY generate.sh\npublic let aeroSpaceAppVersion = "%s"\n' "$VERSION" > Sources/Common/versionGenerated.swift
printf '// FILE IS GENERATED BY generate.sh\npublic let gitHash = "%s"\npublic let gitShortHash = "%s"\n' "$UPSTREAM_COMMIT" "${UPSTREAM_COMMIT:0:7}" > Sources/Common/gitHashGenerated.swift
swift build -c release --arch arm64 --product AeroSpaceApp
swift build -c release --arch arm64 --product aerospace
BIN="$SRC/.build/arm64-apple-macosx/release"

# Keep the untouched upstream app once, for rollback.
if [ ! -d "$ROLLBACK/AeroSpace.app" ] && ! grep -q exrpatch "$APP/Contents/Info.plist"; then
  mkdir -p "$ROLLBACK" && cp -R "$APP" "$ROLLBACK/"
fi

osascript -e 'quit app "AeroSpace"' 2>/dev/null || true
sleep 1; pkill -x AeroSpace 2>/dev/null || true
codesign -d --entitlements :- "$APP" > /tmp/aerospace-entitlements.plist 2>/dev/null || true
cp "$BIN/AeroSpaceApp" "$APP/Contents/MacOS/AeroSpace"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleVersion $VERSION" "$APP/Contents/Info.plist" 2>/dev/null || true
if [ -s /tmp/aerospace-entitlements.plist ]; then
  codesign --force --deep --sign - --entitlements /tmp/aerospace-entitlements.plist "$APP"
else
  codesign --force --deep --sign - "$APP"
fi
# CLI: a real file, not the cask symlink, so it matches the server version.
rm -f /opt/homebrew/bin/aerospace && cp "$BIN/aerospace" /opt/homebrew/bin/aerospace

env -u NO_COLOR open -a AeroSpace
sleep 3
/opt/homebrew/bin/aerospace --version
echo "Ad-hoc signed: the new binary needs one Accessibility approval (System Settings > Privacy & Security > Accessibility: remove AeroSpace, re-add/enable it)."
